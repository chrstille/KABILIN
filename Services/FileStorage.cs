namespace KABILIN.Services
{
    public interface IFileStorage
    {
        Task<(bool Ok, string? Error, string? StoredName)> SaveAsync(IFormFile file);
        Stream? Open(string storedName);
        void Delete(string storedName);
    }

    /// <summary>
    /// Stores uploads in App_Data/uploads (outside wwwroot) under random names.
    /// Files are only ever served through authorised controller actions.
    /// </summary>
    public class FileStorage : IFileStorage
    {
        public const long MaxBytes = 5 * 1024 * 1024;
        public static readonly string[] AllowedExtensions = { ".pdf", ".jpg", ".jpeg", ".png" };

        private readonly string _root;

        public FileStorage(IWebHostEnvironment env)
        {
            _root = Path.Combine(env.ContentRootPath, "App_Data", "uploads");
            Directory.CreateDirectory(_root);
        }

        public async Task<(bool Ok, string? Error, string? StoredName)> SaveAsync(IFormFile file)
        {
            var name = Path.GetFileName(file.FileName);
            if (file.Length == 0)
                return (false, $"\"{name}\" is empty.", null);
            if (file.Length > MaxBytes)
                return (false, $"\"{name}\" is larger than 5 MB.", null);

            var ext = Path.GetExtension(name).ToLowerInvariant();
            if (!AllowedExtensions.Contains(ext))
                return (false, $"\"{name}\" is not a supported file type. Please upload a PDF, JPG or PNG.", null);

            // Check the real file signature, not just the extension.
            var header = new byte[8];
            await using (var probe = file.OpenReadStream())
            {
                var read = await probe.ReadAsync(header.AsMemory(0, header.Length));
                if (read < 4 || !SignatureMatches(ext, header))
                    return (false, $"\"{name}\" does not look like a valid {ext.TrimStart('.').ToUpperInvariant()} file.", null);
            }

            var stored = Guid.NewGuid().ToString("N") + (ext == ".jpeg" ? ".jpg" : ext);
            await using var target = File.Create(Path.Combine(_root, stored));
            await file.CopyToAsync(target);
            return (true, null, stored);
        }

        public Stream? Open(string storedName)
        {
            var path = Resolve(storedName);
            return path != null && File.Exists(path) ? File.OpenRead(path) : null;
        }

        public void Delete(string storedName)
        {
            var path = Resolve(storedName);
            if (path != null && File.Exists(path)) File.Delete(path);
        }

        private string? Resolve(string storedName)
        {
            // Stored names are generated by us; reject anything else (path traversal guard).
            if (string.IsNullOrWhiteSpace(storedName) || storedName != Path.GetFileName(storedName)) return null;
            return Path.Combine(_root, storedName);
        }

        private static bool SignatureMatches(string ext, byte[] h) => ext switch
        {
            ".pdf" => h[0] == 0x25 && h[1] == 0x50 && h[2] == 0x44 && h[3] == 0x46,
            ".jpg" or ".jpeg" => h[0] == 0xFF && h[1] == 0xD8 && h[2] == 0xFF,
            ".png" => h[0] == 0x89 && h[1] == 0x50 && h[2] == 0x4E && h[3] == 0x47,
            _ => false
        };

        public static string ContentTypeFor(string storedName) =>
            Path.GetExtension(storedName).ToLowerInvariant() switch
            {
                ".pdf" => "application/pdf",
                ".png" => "image/png",
                _ => "image/jpeg"
            };
    }
}
